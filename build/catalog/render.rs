//! Generated Rust source for the `Text` enum and the per-locale tables.

use super::locales::LOCALE_TAGS;
use super::model::{Catalog, Category, Value};

/// Renders the generated source from English and the other catalogs, which are given in
/// `LOCALE_TAGS` order with `None` for a locale without a file. Every present catalog must
/// already have passed the parity checks.
pub fn render(catalogs: &[Option<Catalog>]) -> Result<String, String> {
    let Some(english) = catalogs.first().and_then(Option::as_ref) else {
        return Err("the English catalog is required".to_owned());
    };
    let mut out = String::new();
    out.push_str("// Generated by build.rs from assets/i18n/*.txt; do not edit.\n\n");
    render_enum(&mut out, english);
    for catalog in catalogs.iter().flatten() {
        render_table(&mut out, english, catalog)?;
    }
    out.push_str(
        "/// Catalog tables in `Locale::ALL` order; `None` falls back to English.\n\
         static CATALOGS: [Option<&'static [Entry; Text::COUNT]>; Locale::COUNT] = [\n",
    );
    for (tag, catalog) in LOCALE_TAGS.iter().zip(catalogs) {
        match catalog {
            Some(_) => out.push_str(&format!("    Some(&{}),\n", table_name(tag))),
            None => out.push_str("    None,\n"),
        }
    }
    out.push_str("];\n");
    Ok(out)
}

/// Writes the `Text` enum and its inherent items.
fn render_enum(out: &mut String, english: &Catalog) {
    let count = english.items.len();
    out.push_str(
        "/// One interface string, identified by its catalog key; generated from `en-US.txt` in\n\
         /// file order.\n\
         #[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]\n\
         #[allow(dead_code)]\n\
         pub enum Text {\n",
    );
    for item in &english.items {
        out.push_str(&format!(
            "    /// `{}`\n    {},\n",
            item.key,
            variant_name(&item.key)
        ));
    }
    out.push_str("}\n\n#[allow(dead_code)]\nimpl Text {\n");
    out.push_str(&format!(
        "    /// Number of keys.\n    pub const COUNT: usize = {count};\n\n"
    ));
    out.push_str(
        "    /// Every key in catalog order.\n    pub const ALL: [Text; Text::COUNT] = [\n",
    );
    for item in &english.items {
        out.push_str(&format!("        Text::{},\n", variant_name(&item.key)));
    }
    out.push_str("    ];\n\n");
    out.push_str("    /// Dotted catalog key.\n    pub const fn key(self) -> &'static str {\n        match self {\n");
    for item in &english.items {
        out.push_str(&format!(
            "            Text::{} => {:?},\n",
            variant_name(&item.key),
            item.key
        ));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    /// Position in `ALL` and in every catalog table.\n    pub const fn index(self) -> usize {\n        self as usize\n    }\n}\n\n",
    );
}

/// Writes one locale table in English key order.
fn render_table(out: &mut String, english: &Catalog, catalog: &Catalog) -> Result<(), String> {
    out.push_str(&format!(
        "/// Interface text for `{}`.\nstatic {}: [Entry; Text::COUNT] = [\n",
        catalog.tag,
        table_name(catalog.tag)
    ));
    for reference in &english.items {
        let Some(item) = catalog.find(&reference.key) else {
            return Err(format!(
                "{}: missing key `{}` reached the generator",
                catalog.path, reference.key
            ));
        };
        match &item.value {
            Value::Plain(form) => out.push_str(&format!("    Entry::Plain({:?}),\n", form.text)),
            Value::Plural(forms) => {
                let pick =
                    |category: Category| match forms.iter().find(|(known, _)| *known == category) {
                        Some((_, form)) => format!("Some({:?})", form.text),
                        None => "None".to_owned(),
                    };
                let Some((_, other)) = forms.iter().find(|(known, _)| *known == Category::Other)
                else {
                    return Err(format!(
                        "{}:{}: key `{}` has no other form",
                        catalog.path, item.line, item.key
                    ));
                };
                out.push_str(&format!(
                    "    Entry::Plural(&Forms {{ zero: {}, one: {}, two: {}, few: {}, many: {}, other: {:?} }}),\n",
                    pick(Category::Zero),
                    pick(Category::One),
                    pick(Category::Two),
                    pick(Category::Few),
                    pick(Category::Many),
                    other.text
                ));
            }
        }
    }
    out.push_str("];\n\n");
    Ok(())
}

/// Static name for a locale table, such as `CATALOG_ZH_HANS`.
fn table_name(tag: &str) -> String {
    format!("CATALOG_{}", tag.to_ascii_uppercase().replace('-', "_"))
}

/// Enum variant for a key: split at `.` and `_`, capitalize each part, join
/// (`grid.show_details` becomes `GridShowDetails`).
pub fn variant_name(key: &str) -> String {
    let mut name = String::with_capacity(key.len());
    for part in key.split(['.', '_']) {
        let mut characters = part.chars();
        if let Some(first) = characters.next() {
            name.extend(first.to_uppercase());
            name.push_str(characters.as_str());
        }
    }
    name
}
